#!/usr/bin/env python3
"""
Regenerate src/data/acl-list.ts and src/data/afl-list.ts from the published lists.

Sources (saved locally first, then passed as arguments):
  ACL  https://www.eapfoundation.com/vocab/academic/acl/   (2,469 collocations, by headword)
  AFL  https://www.eapfoundation.com/vocab/academic/afl/   (core 207 + spoken 200 + written 200)

Usage:  python3 scripts/import-lists.py <acl.html> <afl.html>

Card ids are slugs of the phrase, so re-running this never renumbers existing
cards and study progress survives a list update.
"""
import html as H
import json
import re
import sys
from pathlib import Path


def cells_of(table_html):
    rows = []
    for r in re.findall(r"<tr[^>]*>(.*?)</tr>", table_html, re.S):
        cells = [
            " ".join(H.unescape(re.sub(r"<[^>]+>", "", c)).replace("\xa0", " ").split())
            for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r, re.S)
        ]
        if cells:
            rows.append(cells)
    return rows


def split_outside_brackets(text):
    """Split a cell on commas, but not on commas inside brackets:
    "closely allied (to, with)" is one entry, not two."""
    parts, depth, current = [], 0, []
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    parts.append("".join(current))
    return parts


# Typos in the published source page, corrected on import.
SOURCE_FIXES = {
    "alternative interpretion": "alternative interpretation",
    "use (the) concept concept": "use (the) concept",
    "use (the) data data": "use (the) data",
    "make(a) judgement": "make (a) judgement",
}


def parse_acl(path):
    """-> [(collocation, [headwords])] in list order, de-duplicated."""
    doc = Path(path).read_text(encoding="utf-8", errors="replace")
    out, index = [], {}
    for row in cells_of(doc):
        if len(row) != 2:
            continue
        head, colls = row
        if not head or head.lower().startswith("headword"):
            continue
        for coll in split_outside_brackets(colls):
            coll = " ".join(coll.split())
            if not coll:
                continue
            coll = SOURCE_FIXES.get(coll, coll)
            key = coll.lower()
            if key in index:
                if head not in index[key][1]:
                    index[key][1].append(head)
                continue
            entry = (coll, [head])
            index[key] = entry
            out.append(entry)
    return out


def parse_afl(path):
    """-> [(formula, sublist, freq_speech, freq_writing, ftw)]"""
    doc = Path(path).read_text(encoding="utf-8", errors="replace")
    out = []
    for m in re.finditer(r"<table.*?</table>", doc, re.S):
        before = " ".join(H.unescape(re.sub(r"<[^>]+>", " ", doc[: m.start()])).split())
        if before.endswith("common in both written and spoken English."):
            sub = "core"
        elif before.endswith("common in spoken English."):
            sub = "spoken"
        elif before.endswith("common in written English."):
            sub = "written"
        else:
            continue
        for row in cells_of(m.group(0)):
            if len(row) < 5 or not row[0].isdigit():
                continue
            _, formula, speech, writing, ftw = row[:5]
            out.append((" ".join(formula.split()), sub, speech, writing, ftw))
    return out


HEADER = """// GENERATED by scripts/import-lists.py — edit the source list, not this file.
// Hand-written meanings and examples live in notes.ts and are matched by phrase.
import { parseList } from './parse'

const RAW = String.raw`
"""


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    acl, afl = parse_acl(sys.argv[1]), parse_afl(sys.argv[2])

    lines = [f"{coll}|{','.join(heads)}" for coll, heads in acl]
    Path("src/data/acl-list.ts").write_text(
        HEADER.replace("parseList", "parseAcl")
        + "\n".join(lines)
        + "\n`\n\nexport const ACL_LIST = parseAcl(RAW)\n",
        encoding="utf-8",
    )

    lines = [f"{f}|{sub}|{sp}|{wr}|{ftw}" for f, sub, sp, wr, ftw in afl]
    Path("src/data/afl-list.ts").write_text(
        HEADER.replace("parseList", "parseAfl")
        + "\n".join(lines)
        + "\n`\n\nexport const AFL_LIST = parseAfl(RAW)\n",
        encoding="utf-8",
    )

    counts = {}
    for _, sub, *_rest in afl:
        counts[sub] = counts.get(sub, 0) + 1
    print(json.dumps({"acl": len(acl), "afl": counts}, indent=2))


if __name__ == "__main__":
    main()
